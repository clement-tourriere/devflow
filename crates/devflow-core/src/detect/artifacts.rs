//! Existing, expensive-to-rebuild paths that may be cloned into a new worktree.
//!
//! Only paths that exist are reported, each with its Git ignore status
//! (ignore rules matched and not tracked). Symlinks are never reported:
//! cloning a link would copy the link, not the data. The scan decides
//! nothing; `recommendation` and `reason` are advice for the proposal layer.
use super::env::is_env_file_name;
use super::facts::{
    ArtifactFact, ArtifactKind, CopyRecommendation, Framework, FrameworkFact, JsProject,
    MigrationFact, MigrationTool,
};
use super::manifest::Discovery;
use super::repo::{Kind, Repo, join};

const MAX_ARTIFACTS: usize = 200;

use ArtifactKind as K;
use CopyRecommendation::{NotRecommended, Recommended};

struct Scanner<'a> {
    repo: &'a Repo,
    out: Vec<ArtifactFact>,
}

impl Scanner<'_> {
    /// Report `path` if it exists as the expected kind.
    fn add(
        &mut self,
        path: String,
        kind: ArtifactKind,
        recommendation: CopyRecommendation,
        reason: &str,
        evidence: Vec<String>,
    ) {
        if self.out.len() >= MAX_ARTIFACTS || self.out.iter().any(|a| a.path == path) {
            return;
        }
        let want_dir = !matches!(kind, K::SecretKey | K::EnvFile);
        let expected = if want_dir { Kind::Dir } else { Kind::File };
        if self.repo.is_symlink(&path) || self.repo.kind(&path) != Some(expected) {
            return;
        }
        let git_ignored = self.repo.git_ignored(&path, want_dir);
        let mut evidence = evidence;
        evidence.insert(0, path.clone());
        self.out.push(ArtifactFact {
            path,
            kind,
            recommendation,
            reason: reason.to_string(),
            git_ignored,
            evidence,
        });
    }
}

pub(super) fn detect(
    repo: &Repo,
    discovery: &Discovery,
    js: &[JsProject],
    frameworks: &[FrameworkFact],
    migrations: &[MigrationFact],
) -> Vec<ArtifactFact> {
    let mut s = Scanner {
        repo,
        out: Vec::new(),
    };
    let framework_paths = |wanted: &[Framework]| -> Vec<String> {
        frameworks
            .iter()
            .filter(|f| wanted.contains(&f.framework))
            .map(|f| f.path.clone())
            .collect()
    };

    // Installed JavaScript dependencies, per package.
    for project in js {
        for package in &project.packages {
            s.add(
                join(&package.path, "node_modules"),
                K::NodeModules,
                Recommended,
                "Installed dependencies are slow to rebuild and clone cheaply on copy-on-write \
                 filesystems; install commands must not delete them.",
                package.evidence.clone(),
            );
        }
    }

    // `.env*` files next to project manifests.
    for project in &discovery.projects {
        for name in project.dir.files().filter(|n| is_env_file_name(n)) {
            s.add(
                join(&project.path, name),
                K::EnvFile,
                Recommended,
                "Local configuration that Git ignores; a new worktree does not receive it.",
                Vec::new(),
            );
        }
    }

    // Per-ecosystem dependency directories.
    for project in &discovery.projects {
        if project.php.present() {
            s.add(
                project.file("vendor"),
                K::ComposerVendor,
                Recommended,
                "Composer dependencies are slow to reinstall and clone cheaply.",
                project.php.files.clone(),
            );
        }
        if project.rb.present() {
            s.add(
                project.file("vendor/bundle"),
                K::BundlerVendor,
                Recommended,
                "Bundler gems installed under vendor/bundle are slow to reinstall.",
                project.rb.files.clone(),
            );
        }
        if project.ex.present() {
            s.add(
                project.file("deps"),
                K::ElixirDeps,
                Recommended,
                "Fetched Mix dependencies are slow to refetch and recompile.",
                project.ex.files.clone(),
            );
        }
    }

    // Prisma clients generated inside the repository.
    for migration in migrations
        .iter()
        .filter(|m| m.tool == MigrationTool::Prisma)
    {
        for output in &migration.generated_outputs {
            s.add(
                output.clone(),
                K::GeneratedCode,
                Recommended,
                "Generated by `prisma generate` and absent from a fresh checkout.",
                migration.config_files.clone(),
            );
        }
    }

    // Application directories: the root plus Rails and Laravel projects.
    let mut app_dirs = vec![".".to_string()];
    for path in framework_paths(&[Framework::Rails, Framework::Laravel]) {
        if !app_dirs.contains(&path) {
            app_dirs.push(path);
        }
    }
    for dir in &app_dirs {
        s.add(
            join(dir, "app/assets/builds"),
            K::AssetBuilds,
            Recommended,
            "Compiled front-end assets the app serves in development.",
            Vec::new(),
        );
        s.add(
            join(dir, "public/build"),
            K::AssetBuilds,
            Recommended,
            "Compiled front-end assets the app serves in development.",
            Vec::new(),
        );
        s.add(
            join(dir, "tmp"),
            K::Tmp,
            NotRecommended,
            "Runtime scratch files, sockets and pids of the running app.",
            Vec::new(),
        );
        s.add(
            join(dir, "log"),
            K::Log,
            NotRecommended,
            "Logs written by the source checkout's runs.",
            Vec::new(),
        );
        s.add(
            join(dir, "bootstrap/cache"),
            K::BootstrapCache,
            NotRecommended,
            "Cached framework configuration with absolute paths; regenerate it in the worktree.",
            Vec::new(),
        );
        s.add(
            join(dir, "storage"),
            K::Storage,
            NotRecommended,
            "Application data (uploads, sessions, logs) owned by a running app; seed it deliberately.",
            Vec::new(),
        );
    }

    // Rails secret keys.
    for dir in framework_paths(&[Framework::Rails]) {
        s.add(
            join(&dir, "config/master.key"),
            K::SecretKey,
            Recommended,
            "Decrypts Rails credentials; Git ignores it, so a new worktree lacks it.",
            Vec::new(),
        );
        let credentials = join(&dir, "config/credentials");
        if repo.is_dir(&credentials) {
            let index = repo.list(&credentials);
            for name in index.files().filter(|n| n.ends_with(".key")).take(10) {
                s.add(
                    join(&credentials, name),
                    K::SecretKey,
                    Recommended,
                    "Decrypts Rails credentials; Git ignores it, so a new worktree lacks it.",
                    Vec::new(),
                );
            }
        }
    }

    // Present, but cloning would be wrong or wasteful.
    s.add(
        ".venv".into(),
        K::PythonVenv,
        NotRecommended,
        "Virtual environments embed absolute paths and are not relocatable; recreate with the package manager.",
        Vec::new(),
    );
    for project in &discovery.projects {
        if project.path != "." && project.py.present() {
            s.add(
                project.file(".venv"),
                K::PythonVenv,
                NotRecommended,
                "Virtual environments embed absolute paths and are not relocatable; recreate with the package manager.",
                Vec::new(),
            );
        }
    }
    for path in framework_paths(&[Framework::NextJs]) {
        s.add(
            join(&path, ".next"),
            K::NextCache,
            NotRecommended,
            "A build cache with absolute paths that Next.js regenerates.",
            Vec::new(),
        );
    }
    for path in framework_paths(&[Framework::Rust]) {
        s.add(
            join(&path, "target"),
            K::CargoTarget,
            NotRecommended,
            "Very large build output keyed to absolute paths; cargo rebuilds it incrementally.",
            Vec::new(),
        );
    }
    s.out
}
