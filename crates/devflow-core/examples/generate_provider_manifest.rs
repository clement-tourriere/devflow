//! Generate frontend contracts directly from the core provider catalog.
use anyhow::{Context, Result};
use serde_json::Value;
use std::{collections::BTreeSet, path::Path};

fn union(values: impl Iterator<Item = String>) -> String {
    values
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>()
        .join(" | ")
}
fn quoted(value: &Value) -> String {
    serde_json::to_string(value).expect("descriptor is serializable")
}
fn strings(value: &Value) -> String {
    value
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_str().unwrap())
        .collect::<Vec<_>>()
        .join(", ")
}
fn main() -> Result<()> {
    let args: Vec<_> = std::env::args().skip(1).collect();
    anyhow::ensure!(
        args.is_empty() || args == ["--check"],
        "usage: generate_provider_manifest [--check]"
    );
    let check = !args.is_empty();
    let catalog = serde_json::to_value(devflow_core::services::descriptor::providers())?;
    let catalog = catalog
        .as_array()
        .context("provider catalog is not an array")?;
    let first = catalog.first().context("provider catalog is empty")?;
    let operations = first["operations"].as_object().unwrap();
    let mut ts =
        "// Generated by the generate_provider_manifest Rust example; edit the Rust descriptor.\n"
            .to_string();
    ts += &format!(
        "export type ProviderName = {};\n",
        union(catalog.iter().map(|p| quoted(&p["provider"])))
    );
    ts += &format!(
        "export type ServiceType = {};\n",
        union(
            catalog
                .iter()
                .flat_map(|p| p["service_types"].as_array().unwrap().iter().map(quoted))
        )
    );
    ts += &format!(
        "export type ServiceOperation = {};\n",
        union(
            operations
                .keys()
                .map(|key| quoted(&Value::String(key.clone())))
        )
    );
    ts += "export interface ProviderDescriptor {\n";
    for key in first.as_object().unwrap().keys() {
        let kind = if key == "operations" {
            "Record<ServiceOperation, boolean>".to_string()
        } else {
            union(catalog.iter().map(|p| {
                match &p[key] {
                    Value::Null => "null",
                    Value::Bool(_) => "boolean",
                    Value::Number(_) => "number",
                    Value::String(_) => "string",
                    Value::Array(_) => "string[]",
                    _ => panic!("unsupported descriptor field {key}"),
                }
                .to_string()
            }))
        };
        ts += &format!("  {key}: {kind};\n");
    }
    ts += "}\n";
    let mut md = "---\ntitle: Provider catalog\ndescription: Generated provider configuration and operation contracts.\n---\n\nGenerated from the core provider descriptors, also exposed by `devflow --json capabilities`. Build availability is reported at runtime in `available`; this table lists the catalog across builds. Plugins negotiate their own capabilities. Local Redis without a `generic` block retains legacy shared allocation.\n\n| Provider | Services | Data strategy | Operations | Required setup | Allocation limit |\n| --- | --- | --- | --- | --- | --- |\n".to_string();
    for provider in catalog {
        let operations = provider["operations"]
            .as_object()
            .unwrap()
            .iter()
            .filter(|(_, value)| value.as_bool() == Some(true))
            .map(|(key, _)| key.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        let required = strings(&provider["required_configuration"]);
        md += &format!(
            "| {}{} | {} | {} | {} | {} | {} |\n",
            provider["provider"].as_str().unwrap(),
            if provider["experimental"] == true {
                " (experimental)"
            } else {
                ""
            },
            strings(&provider["service_types"]),
            provider["data_strategy"].as_str().unwrap(),
            if operations.is_empty() {
                "none / negotiated"
            } else {
                &operations
            },
            if required.is_empty() {
                "none"
            } else {
                &required
            },
            provider["allocation_limit"]
                .as_u64()
                .map(|n| n.to_string())
                .unwrap_or_else(|| "—".into())
        );
    }
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (path, content) in [
        ("ui/src/types/providers.generated.ts", ts),
        (
            "docs-site/src/content/docs/reference/provider-catalog.md",
            md,
        ),
    ] {
        if check {
            anyhow::ensure!(
                std::fs::read_to_string(root.join(path))? == content,
                "stale generated file: {path}"
            );
        } else {
            std::fs::write(root.join(path), content)?;
        }
    }
    Ok(())
}
