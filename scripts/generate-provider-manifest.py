#!/usr/bin/env python3
"""Generate frontend provider types and reference facts from the tested CLI."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--binary", type=Path, default=ROOT / "target/debug/devflow")
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
with tempfile.TemporaryDirectory(prefix="devflow-manifest-") as directory:
    env = dict(os.environ, DEVFLOW_CONFIG_DIR=directory)
    catalog = json.loads(subprocess.check_output([str(args.binary.resolve()), "--json", "capabilities"], cwd=directory, env=env))["providers"]
assert catalog and all(item["schema_version"] == 1 for item in catalog)

def union(values):
    return " | ".join(json.dumps(v) for v in sorted(set(values)))

def field_type(values):
    types = set()
    for value in values:
        if value is None:
            types.add("null")
        elif isinstance(value, bool):
            types.add("boolean")
        elif isinstance(value, (int, float)):
            types.add("number")
        elif isinstance(value, str):
            types.add("string")
        elif isinstance(value, list):
            types.add("string[]")
        else:
            raise ValueError(f"unhandled descriptor field {value!r}")
    return " | ".join(sorted(types))

operations = sorted(catalog[0]["operations"])
assert all(sorted(item["operations"]) == operations for item in catalog)
ts = "// Generated by scripts/generate-provider-manifest.py; edit the Rust descriptor.\n"
ts += "export type ProviderName = " + union(item["provider"] for item in catalog) + ";\n"
ts += "export type ServiceType = " + union(t for item in catalog for t in item["service_types"]) + ";\n"
ts += "export type ServiceOperation = " + union(operations) + ";\n"
ts += "export interface ProviderDescriptor {\n"
for key in catalog[0]:
    kind = "Record<ServiceOperation, boolean>" if key == "operations" else field_type([item[key] for item in catalog])
    ts += f"  {key}: {kind};\n"
ts += "}\n"
md = """---
title: Provider catalog
description: Generated provider configuration and operation contracts.
---

Generated from `devflow --json capabilities`. Build availability is reported at runtime in `available`; this table lists the catalog across builds. Plugins negotiate their own capabilities. Local Redis without a `generic` block retains legacy shared allocation.

| Provider | Services | Data strategy | Operations | Required setup | Allocation limit |
| --- | --- | --- | --- | --- | --- |
"""
for item in catalog:
    md += "| " + " | ".join([
        item["provider"] + (" (experimental)" if item["experimental"] else ""),
        ", ".join(item["service_types"]), item["data_strategy"],
        ", ".join(k for k, v in item["operations"].items() if v) or "none / negotiated",
        ", ".join(item["required_configuration"]) or "none", str(item["allocation_limit"] or "—")
    ]) + " |\n"
for path, content in [(ROOT / "ui/src/types/providers.generated.ts", ts), (ROOT / "docs-site/src/content/docs/reference/provider-catalog.md", md)]:
    if args.check:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"stale generated file: {path.relative_to(ROOT)}")
    else:
        path.write_text(content)
